/*
  008_check_volume_data.sql
  Checks the data generated by 007 in TraceabilityDev. READ ONLY: it changes nothing.

  - Runs ONLY on TraceabilityDev. The name is written in the script, so SQLCMD
    mode is not needed.
  - Replayable at any time. Contains no INSERT, UPDATE, DROP, TRUNCATE or DELETE.
  - Works on the sample AND on the full set: the expected numbers are computed from
    the number of batches found (the same formulas as 007).
    For 1000000 batches: SHIPPED 600000, PACKED 150000, SORTED 150000,
    RECEIVED 100000, and 3250000 movements.
  - Part A: the checks. checks_ok must equal checks_total.
  - Part B: information (not pass/fail): batches per farm group.
  - Part C: information: size of each table and index, size of the files, free space.
    It is used to measure the size per row on the sample, before the full set.
  - The checks 19 to 26 read the whole journal: they can take some seconds.
*/

USE TraceabilityDev;
GO

SET NOCOUNT ON;

IF DB_NAME() <> N'TraceabilityDev'
BEGIN
    THROW 50001, N'Wrong database. This check runs only on TraceabilityDev. Nothing was done.', 1;
END;

DECLARE @NB INT = (SELECT COUNT(*) FROM trace.Batch);

IF @NB = 0
BEGIN
    THROW 50003, N'There is no batch in TraceabilityDev. Run 007 first.', 1;
END;

/* ---------- Expected numbers, from the number of batches ---------- */

DECLARE @ExpShipped  INT = LEAST(@NB, 600000);
DECLARE @ExpPacked   INT = GREATEST(0, LEAST(@NB, 750000) - 600000);
DECLARE @ExpSorted   INT = GREATEST(0, LEAST(@NB, 900000) - 750000);
DECLARE @ExpReceived INT = GREATEST(0, @NB - 900000);
DECLARE @ExpMov      INT = 4 * @ExpShipped + 3 * @ExpPacked + 2 * @ExpSorted + @ExpReceived;

/* ---------- Measures ---------- */

DECLARE @Farms     INT = (SELECT COUNT(*) FROM trace.Farm);
DECLARE @Stations  INT = (SELECT COUNT(*) FROM trace.Station);
DECLARE @Caps      INT = (SELECT COUNT(*) FROM trace.StationCapability);

DECLARE @Shipped INT, @Packed INT, @Sorted INT, @Received INT;
SELECT @Shipped  = ISNULL(SUM(CASE WHEN Status = N'SHIPPED'  THEN 1 ELSE 0 END), 0),
       @Packed   = ISNULL(SUM(CASE WHEN Status = N'PACKED'   THEN 1 ELSE 0 END), 0),
       @Sorted   = ISNULL(SUM(CASE WHEN Status = N'SORTED'   THEN 1 ELSE 0 END), 0),
       @Received = ISNULL(SUM(CASE WHEN Status = N'RECEIVED' THEN 1 ELSE 0 END), 0)
FROM trace.Batch;

DECLARE @BadCodes INT = (SELECT COUNT(*) FROM trace.Batch
                         WHERE BatchCode NOT LIKE N'LOT-[0-9][0-9][0-9][0-9][0-9][0-9][0-9]');
DECLARE @MinLot INT, @MaxLot INT;
SELECT @MinLot = MIN(TRY_CAST(SUBSTRING(BatchCode, 5, 7) AS INT)),
       @MaxLot = MAX(TRY_CAST(SUBSTRING(BatchCode, 5, 7) AS INT))
FROM trace.Batch
WHERE BatchCode LIKE N'LOT-[0-9][0-9][0-9][0-9][0-9][0-9][0-9]';

DECLARE @BigFarmLots INT = (SELECT COUNT(*)
                            FROM trace.Batch AS b
                            JOIN trace.Farm AS f ON f.FarmId = b.FarmId
                            WHERE f.Code <= N'F020');

DECLARE @MinHarvest DATE, @MaxHarvest DATE;
SELECT @MinHarvest = MIN(HarvestDate), @MaxHarvest = MAX(HarvestDate) FROM trace.Batch;
DECLARE @ExpMaxHarvest DATE =
    DATEADD(DAY, CAST((CAST(@NB AS BIGINT) - 1) * 729 / 999999 AS INT), CAST('20241020' AS DATE));

DECLARE @Mov INT, @MovRec INT, @MovSort INT, @MovPack INT, @MovShip INT;
SELECT @Mov     = COUNT(*),
       @MovRec  = ISNULL(SUM(CASE WHEN MovementType = N'RECEPTION' THEN 1 ELSE 0 END), 0),
       @MovSort = ISNULL(SUM(CASE WHEN MovementType = N'SORTING'   THEN 1 ELSE 0 END), 0),
       @MovPack = ISNULL(SUM(CASE WHEN MovementType = N'PACKING'   THEN 1 ELSE 0 END), 0),
       @MovShip = ISNULL(SUM(CASE WHEN MovementType = N'SHIPMENT'  THEN 1 ELSE 0 END), 0)
FROM trace.Movement;

DECLARE @BatchesWithMov INT = (SELECT COUNT(DISTINCT BatchId) FROM trace.Movement);

DECLARE @NoCapability INT = (SELECT COUNT(*)
                             FROM trace.Movement AS m
                             WHERE NOT EXISTS (SELECT 1 FROM trace.StationCapability AS c
                                               WHERE c.StationId = m.StationId
                                                 AND c.MovementType = m.MovementType));

DECLARE @Untrusted INT =
      (SELECT COUNT(*) FROM sys.foreign_keys    WHERE is_not_trusted = 1 AND SCHEMA_NAME(schema_id) = N'trace')
    + (SELECT COUNT(*) FROM sys.check_constraints WHERE is_not_trusted = 1 AND SCHEMA_NAME(schema_id) = N'trace');

-- One pass over the journal, batch by batch, movement by movement (journal order).
DECLARE @BadOrder INT, @QtyUp INT, @BadLoss INT, @TimeBack INT,
        @RecepOut INT, @LastQty INT, @LastStatus INT;

WITH m AS
(
    SELECT BatchId, MovementType, QuantityKg, OccurredAt,
           ROW_NUMBER() OVER (PARTITION BY BatchId ORDER BY MovementId) AS rn,
           LAG(QuantityKg)  OVER (PARTITION BY BatchId ORDER BY MovementId) AS prev_qty,
           LAG(OccurredAt)  OVER (PARTITION BY BatchId ORDER BY MovementId) AS prev_at,
           LEAD(MovementId) OVER (PARTITION BY BatchId ORDER BY MovementId) AS next_id
    FROM trace.Movement
)
SELECT
    -- the k-th movement of a batch has the k-th type: RECEPTION, SORTING, PACKING, SHIPMENT
    @BadOrder = ISNULL(SUM(CASE WHEN m.rn <>
                                     CASE m.MovementType WHEN N'RECEPTION' THEN 1 WHEN N'SORTING'  THEN 2
                                                         WHEN N'PACKING'   THEN 3 WHEN N'SHIPMENT' THEN 4 END
                                THEN 1 ELSE 0 END), 0),
    -- the quantity never goes up
    @QtyUp = ISNULL(SUM(CASE WHEN m.prev_qty IS NOT NULL AND m.QuantityKg > m.prev_qty
                             THEN 1 ELSE 0 END), 0),
    -- the loss of a step is at most 10 % (no tolerance: 007 rounds so that it holds)
    @BadLoss = ISNULL(SUM(CASE WHEN m.prev_qty IS NOT NULL AND m.QuantityKg < m.prev_qty * 0.90
                               THEN 1 ELSE 0 END), 0),
    -- each movement is later than the previous one
    @TimeBack = ISNULL(SUM(CASE WHEN m.prev_at IS NOT NULL AND m.OccurredAt <= m.prev_at
                                THEN 1 ELSE 0 END), 0),
    -- the first quantity is between 100.00 and 1000.00 kg
    @RecepOut = ISNULL(SUM(CASE WHEN m.rn = 1 AND (m.QuantityKg < 100.00 OR m.QuantityKg > 1000.00)
                                THEN 1 ELSE 0 END), 0),
    -- the batch quantity is the one of its last movement
    @LastQty = ISNULL(SUM(CASE WHEN m.next_id IS NULL AND m.QuantityKg <> b.QuantityKg
                               THEN 1 ELSE 0 END), 0),
    -- the batch status matches the type of its last movement
    @LastStatus = ISNULL(SUM(CASE WHEN m.next_id IS NULL
                                   AND b.Status <>
                                       CASE m.MovementType WHEN N'RECEPTION' THEN N'RECEIVED'
                                                           WHEN N'SORTING'   THEN N'SORTED'
                                                           WHEN N'PACKING'   THEN N'PACKED'
                                                           WHEN N'SHIPMENT'  THEN N'SHIPPED' END
                                  THEN 1 ELSE 0 END), 0)
FROM m
JOIN trace.Batch AS b ON b.BatchId = m.BatchId;

/* ---------- Part A: the checks ---------- */

DECLARE @Checks TABLE
(
    check_no   INT IDENTITY(1,1),
    check_name NVARCHAR(120),
    expected   NVARCHAR(40),
    actual     NVARCHAR(40)
);

INSERT @Checks (check_name, expected, actual) VALUES
 (N'Farms',                                       N'200',                     CAST(@Farms AS NVARCHAR(40))),
 (N'Stations',                                    N'30',                      CAST(@Stations AS NVARCHAR(40))),
 (N'Station functions',                           N'40',                      CAST(@Caps AS NVARCHAR(40))),
 (N'Batch codes not like LOT-nnnnnnn',            N'0',                       CAST(@BadCodes AS NVARCHAR(40))),
 (N'First batch number',                          N'1',                       CAST(ISNULL(@MinLot, -1) AS NVARCHAR(40))),
 (N'Last batch number = number of batches',       CAST(@NB AS NVARCHAR(40)),  CAST(ISNULL(@MaxLot, -1) AS NVARCHAR(40))),
 (N'Batches SHIPPED',                             CAST(@ExpShipped AS NVARCHAR(40)),  CAST(@Shipped AS NVARCHAR(40))),
 (N'Batches PACKED',                              CAST(@ExpPacked AS NVARCHAR(40)),   CAST(@Packed AS NVARCHAR(40))),
 (N'Batches SORTED',                              CAST(@ExpSorted AS NVARCHAR(40)),   CAST(@Sorted AS NVARCHAR(40))),
 (N'Batches RECEIVED',                            CAST(@ExpReceived AS NVARCHAR(40)), CAST(@Received AS NVARCHAR(40))),
 (N'Batches of the 20 big farms (F001-F020)',     CAST((@NB + 1) / 2 AS NVARCHAR(40)), CAST(@BigFarmLots AS NVARCHAR(40))),
 (N'Oldest harvest date',                         N'2024-10-20',              CONVERT(NVARCHAR(40), @MinHarvest, 23)),
 (N'Newest harvest date',                         CONVERT(NVARCHAR(40), @ExpMaxHarvest, 23), CONVERT(NVARCHAR(40), @MaxHarvest, 23)),
 (N'Movements in all',                            CAST(@ExpMov AS NVARCHAR(40)),      CAST(@Mov AS NVARCHAR(40))),
 (N'Movements RECEPTION',                         CAST(@NB AS NVARCHAR(40)),          CAST(@MovRec AS NVARCHAR(40))),
 (N'Movements SORTING',                           CAST(@ExpShipped + @ExpPacked + @ExpSorted AS NVARCHAR(40)), CAST(@MovSort AS NVARCHAR(40))),
 (N'Movements PACKING',                           CAST(@ExpShipped + @ExpPacked AS NVARCHAR(40)), CAST(@MovPack AS NVARCHAR(40))),
 (N'Movements SHIPMENT',                          CAST(@ExpShipped AS NVARCHAR(40)),  CAST(@MovShip AS NVARCHAR(40))),
 (N'Batches that have at least one movement',     CAST(@NB AS NVARCHAR(40)),          CAST(@BatchesWithMov AS NVARCHAR(40))),
 (N'Movements out of order (type k is not the k-th)', N'0',                       CAST(@BadOrder AS NVARCHAR(40))),
 (N'Movements whose quantity goes up',            N'0',                           CAST(@QtyUp AS NVARCHAR(40))),
 (N'Movements that lose more than 10 %',          N'0',                           CAST(@BadLoss AS NVARCHAR(40))),
 (N'Movements not later than the previous one',   N'0',                           CAST(@TimeBack AS NVARCHAR(40))),
 (N'First quantity outside 100.00-1000.00 kg',    N'0',                           CAST(@RecepOut AS NVARCHAR(40))),
 (N'Batch quantity different from its last movement', N'0',                       CAST(@LastQty AS NVARCHAR(40))),
 (N'Batch status different from its last movement',   N'0',                       CAST(@LastStatus AS NVARCHAR(40))),
 (N'Movements at a station without the function', N'0',                           CAST(@NoCapability AS NVARCHAR(40))),
 (N'Foreign keys and checks not trusted',         N'0',                           CAST(@Untrusted AS NVARCHAR(40)));

SELECT check_no,
       check_name,
       expected,
       actual,
       CASE WHEN expected = actual THEN N'OK' ELSE N'ATTENTION' END AS outcome
FROM @Checks
ORDER BY check_no;

SELECT COUNT(*) AS checks_total,
       SUM(CASE WHEN expected = actual THEN 1 ELSE 0 END) AS checks_ok
FROM @Checks;

/* ---------- Part B: information, batches per farm group ---------- */
-- Full set: big farms 25000 each (500000 in all); the other 180 farms 2777 or 2778.

WITH per_farm AS
(
    SELECT f.Code, COUNT(b.BatchId) AS lots
    FROM trace.Farm AS f
    LEFT JOIN trace.Batch AS b ON b.FarmId = f.FarmId
    GROUP BY f.Code
)
SELECT CASE WHEN Code <= N'F020' THEN N'big farms (F001-F020)' ELSE N'other farms (F021-F200)' END AS farm_group,
       COUNT(*)  AS farms,
       MIN(lots) AS min_lots_per_farm,
       MAX(lots) AS max_lots_per_farm,
       SUM(lots) AS lots
FROM per_farm
GROUP BY CASE WHEN Code <= N'F020' THEN N'big farms (F001-F020)' ELSE N'other farms (F021-F200)' END;

/* ---------- Part C: information, sizes and free space ---------- */

-- Size of each table and each index (8 KB pages). used_mb is the space really used,
-- reserved_mb the space set aside. Divide by row_count to get the size per row.
SELECT t.name AS table_name,
       ISNULL(i.name, N'(heap)') AS index_name,
       i.type_desc,
       SUM(ps.row_count) AS row_count,
       CAST(SUM(ps.used_page_count)     * 8 / 1024.0 AS DECIMAL(12,2)) AS used_mb,
       CAST(SUM(ps.reserved_page_count) * 8 / 1024.0 AS DECIMAL(12,2)) AS reserved_mb
FROM sys.dm_db_partition_stats AS ps
JOIN sys.tables  AS t ON t.object_id = ps.object_id
JOIN sys.schemas AS s ON s.schema_id = t.schema_id AND s.name = N'trace'
JOIN sys.indexes AS i ON i.object_id = ps.object_id AND i.index_id = ps.index_id
GROUP BY t.name, i.name, i.type_desc, i.index_id
ORDER BY t.name, i.index_id;

-- Size of the database files.
SELECT name AS file_name, type_desc,
       CAST(size * 8 / 1024.0 AS DECIMAL(12,2)) AS size_mb
FROM sys.database_files
ORDER BY type_desc, name;

-- Free space on the volume(s) of the database files.
SELECT DISTINCT vs.volume_mount_point,
       CAST(vs.total_bytes     / 1073741824.0 AS DECIMAL(10,2)) AS total_gb,
       CAST(vs.available_bytes / 1073741824.0 AS DECIMAL(10,2)) AS free_gb
FROM sys.master_files AS mf
CROSS APPLY sys.dm_os_volume_stats(mf.database_id, mf.file_id) AS vs
WHERE mf.database_id = DB_ID();
GO
